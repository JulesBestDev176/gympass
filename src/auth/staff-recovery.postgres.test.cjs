require('ts-node/register/transpile-only');
const {test}=require('node:test');const assert=require('node:assert/strict');const {PrismaClient}=require('@prisma/client');
const {ConfigService}=require('@nestjs/config');const {JwtService}=require('@nestjs/jwt');
const {PasswordRecoveryService}=require('./password-recovery.service.ts');const {AuthService}=require('./auth.service.ts');
const {JwtStrategy}=require('./strategies/jwt.strategy.ts');const {UsersService}=require('../users/users.service.ts');
const url=process.env.STAFF_AUTH_TEST_DATABASE_URL;

test('PostgreSQL: scoped phone uniqueness, concurrent recovery, session revocation and admin renewal', {skip:!url},async(t)=>{
 const parsed=new URL(url);
 assert.equal(parsed.hostname,'127.0.0.1');assert.equal(parsed.port,'54391');assert.equal(parsed.pathname,'/gympass_auth_tests');
 const db=new PrismaClient({datasources:{db:{url}}});t.after(()=>db.$disconnect());
 const suffix=Date.now().toString();
 const g1=await db.gym.create({data:{nom:'Auth Test One '+suffix,slug:'auth-one-'+suffix}});
 const g2=await db.gym.create({data:{nom:'Auth Test Two '+suffix,slug:'auth-two-'+suffix}});
 const otpMessages=[],credentials=[];
 const whatsapp={sendOtp:async(...args)=>{otpMessages.push(args);return{status:'accepted'};},sendCredentials:async(...args)=>{credentials.push(args);return{status:'accepted'};}};
 const users=new UsersService(db,whatsapp);const cfg=new ConfigService({JWT_SECRET:'isolated-postgres-auth-test'});const jwt=new JwtService({secret:cfg.get('JWT_SECRET')});
 const recovery=new PasswordRecoveryService(db,cfg,whatsapp);const auth=new AuthService(db,jwt,cfg,whatsapp,recovery);const strategy=new JwtStrategy(cfg,db);
 const input={prenom:'Awa',nom:'Diop',telephone:'77 123 45 67',password:'Original secure pass'};
 const user=await users.create(g1.id,input);
 await assert.rejects(users.create(g1.id,{...input,prenom:'Another'}),e=>e.getStatus?.()===409);
 await users.create(g2.id,input);
 assert.equal((await db.user.findUnique({where:{id:user.id}})).telephone,'+221771234567');
 // The database index protects concurrent writers even without application checks.
 await assert.rejects(db.user.create({data:{gymId:g1.id,prenom:'Other',nom:'Test',email:`duplicate-${suffix}@test.invalid`,telephone:'+221771234567',passwordHash:'test-only'}}),e=>e.code==='P2002');
 const old=await auth.login({email:user.email,password:input.password});
 await recovery.request(user.email);await new Promise(resolve=>setImmediate(resolve));assert.equal(otpMessages.length,1);
 const grants=await Promise.allSettled([1,2].map(()=>recovery.verify(user.email,otpMessages[0][1])));
 assert.equal(grants.filter(x=>x.status==='fulfilled').length,1);
 const grant=grants.find(x=>x.status==='fulfilled').value.resetToken;
 const resets=await Promise.allSettled([1,2].map(()=>auth.resetPassword(user.email,grant,'New secure pass 2026','New secure pass 2026')));
 assert.equal(resets.filter(x=>x.status==='fulfilled').length,1);
 const session=resets.find(x=>x.status==='fulfilled').value;
 assert.equal(session.mustChangePassword,false);assert.equal(session.user.id,user.id);
 assert.equal(jwt.verify(session.accessToken).authVersion,1);
 await assert.rejects(strategy.validate(jwt.verify(old.accessToken)),e=>e.getStatus?.()===401);
 await assert.rejects(auth.refresh(old.refreshToken),e=>e.getStatus?.()===401);
 const refreshed=await auth.refresh(session.refreshToken);
 assert.notEqual(refreshed.refreshToken,session.refreshToken);
 await assert.rejects(auth.refresh(session.refreshToken),e=>e.getStatus?.()===401);
 assert.equal((await strategy.validate(jwt.verify(refreshed.accessToken))).id,user.id);
 await assert.rejects(users.renewPassword(g1.id,user.id),e=>e.getStatus?.()===429);
 await db.user.update({where:{id:user.id},data:{passwordRenewedAt:new Date(Date.now()-61000)}});
 const renewed=await users.renewPassword(g1.id,user.id);
 assert.equal(renewed.whatsapp.status,'accepted');assert.equal(credentials.length,3);
 assert.equal(renewed.user.mustChangePassword,true);
 assert.equal(renewed.user.passwordHash,undefined);
 await assert.rejects(strategy.validate(jwt.verify(refreshed.accessToken)),e=>e.getStatus?.()===401);
 const temporary=credentials.at(-1)[2];
 const temporarySession=await auth.login({email:user.email,password:temporary});assert.equal(temporarySession.mustChangePassword,true);
 const chosen=await auth.forceChangePassword(user.id,'My new personal password');assert.equal(chosen.mustChangePassword,false);
 await assert.rejects(strategy.validate(jwt.verify(temporarySession.accessToken)),e=>e.getStatus?.()===401);
 assert.equal((await strategy.validate(jwt.verify(chosen.accessToken))).id,user.id);
 await auth.logout(user.id);await assert.rejects(auth.refresh(chosen.refreshToken));
});
